import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { PROFILE, PROFILES } from './deploymentProfiles.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const PROFILE_FILES = [
  'contracts/profiles/Selected.sol', 'contracts/Coinflip.sol',
  'contracts/DegenerusGame.sol', 'contracts/CrapsBattle.sol',
  'test/helpers/CoinflipStakeSetter.sol', 'test/fuzz/helpers/DeployProtocol.sol',
  'test/helpers/BoundedDeployProtocol.sol', 'test/fork/ForkDeployProtocol.sol',
  'test/helpers/ProfileModules.sol',
];

/** Resolve inheritance and constructor shapes before compiling. No on-chain profile flag exists. */
export function selectProfile({ check = false } = {}) {
  function write(file, text) {
    const target = path.join(root, file);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) {
        throw new Error(`Stale ${PROFILE} generated file: ${file}`);
      }
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, text);
    }
  }
  const banner = '// SPDX-License-Identifier: AGPL-3.0-only\npragma solidity 0.8.38;\n\n';
  const prefix = PROFILE === 'eip170' ? 'Eip170' : 'Glamsterdam';
  const gameModules = PROFILES[PROFILE].filter(row => !row.aliases.includes('GAME') &&
    row.aliases.some(key => key.startsWith('GAME_') && key.endsWith('_MODULE')));
  const crapsModules = PROFILES[PROFILE].filter(row => !row.aliases.includes('CRAPS') &&
    row.aliases.some(key => ['CRAPS_ENGINE', 'CRAPS_LIFECYCLE_MODULE'].includes(key)));
  const moduleRows = [...gameModules, ...crapsModules];
  const sources = fs.readdirSync(path.join(root, 'contracts'), {recursive: true});
  const install = rows => rows.map(row =>
    `        vm.etch(ContractAddresses.${row.key}, vm.getDeployedCode("${row.contract}.sol:${row.contract}"));\n`).join('');
  write('test/helpers/ProfileModules.sol', banner +
    '// Generated selected worker runtimes for standalone fixtures; no storage initialization.\n' +
    'import {Vm} from "forge-std/Vm.sol";\n' +
    'import {ContractAddresses} from "../../contracts/ContractAddresses.sol";\n' +
    moduleRows.map(row => {
      const matches = sources.filter(file => path.basename(file) === `${row.contract}.sol`);
      if (matches.length !== 1) throw new Error(`Ambiguous module source: ${row.contract}`);
      return `import {${row.contract}} from "../../contracts/${matches[0]}";\n`;
    }).join('') + '\nlibrary ProfileModules {\n' +
    '    function installGame(Vm vm) internal {\n' + install(gameModules) + '    }\n' +
    '    function installCraps(Vm vm) internal {\n' + install(crapsModules) + '    }\n}\n');
  write('contracts/profiles/Selected.sol', banner + '// Generated by scripts/select-profile.js; default profile: eip170.\n' +
    ['Game', 'Coinflip', 'Craps'].map(name =>
      `import {${prefix}${name} as Selected${name}} from "./${PROFILE}/${prefix}${name}.sol";\n`).join('') +
    `import {${prefix}${PROFILE === 'eip170' ? 'CrapsEngine' : 'Craps'} as SelectedCrapsEngine} from "./${PROFILE}/${prefix}${PROFILE === 'eip170' ? 'CrapsEngine' : 'Craps'}.sol";\n`);
  // Name each base directly in its importing source. Re-exported import aliases
  // compile in solc but Slither 0.11.5 cannot resolve them as inherited contracts.
  write('contracts/DegenerusGame.sol', banner +
    `import {${prefix}Game} from "./profiles/${PROFILE}/${prefix}Game.sol";\n` +
    'import {IDegenerusVaultOwnerGame} from "./modules/GameFacade.sol";\n\n' +
    `contract DegenerusGame is ${prefix}Game {}\n`);
  write('contracts/CrapsBattle.sol', banner +
    `import {${prefix}Craps} from "./profiles/${PROFILE}/${prefix}Craps.sol";\n` +
    'import {ICrapsEngine, IFlipCoin, IVaultOwnership, IGameCraps, IHighRollerReserve, ICoinflipStake, IReadCohortLifecycle} from "./CrapsInterfaces.sol";\n\n' +
    `contract CrapsBattle is ${prefix}Craps {}\n`);
  const ctor = PROFILE === 'glamsterdam'
    ? '    constructor(address[] memory owners, bytes32[] memory codes, uint8[] memory kicks,\n' +
      `        address[] memory players, bytes32[] memory refs) ${prefix}Coinflip(owners, codes, kicks, players, refs) {}\n`
    : '';
  write('contracts/Coinflip.sol', banner +
    `import {${prefix}Coinflip} from "./profiles/${PROFILE}/${prefix}Coinflip.sol";\n` +
    'import {IFLIP, IWWXRP, IDegenerusRecordBounty} from "./modules/CoinflipCore.sol";\n\n' +
    `contract Coinflip is ${prefix}Coinflip {\n` + ctor + '}\n');
  const setterFile = 'test/helpers/CoinflipStakeSetter.sol';
  const args = PROFILE === 'glamsterdam'
    ? 'new address[](0), new bytes32[](0), new uint8[](0), new address[](0), new bytes32[](0)' : '';
  write(setterFile, fs.readFileSync(path.join(root, setterFile), 'utf8')
    .replace(/constructor\(\) Coinflip\([^\n]*\) \{\}/, `constructor() Coinflip(${args}) {}`));
  for (const [profile, deployments] of Object.entries(PROFILES)) {
    write(`deployments/${profile}.json`, JSON.stringify({ profile, deployments }, null, 2) + '\n');
    write(`scripts/deploy-${profile}.js`,
      `// Generated profile entry point.\nprocess.env.PROFILE = '${profile}';\nawait import('./deploy.js');\n`);
  }
  execFileSync(process.execPath, ['scripts/consolidation/generate-fixtures.js', ...(check ? ['--check'] : [])],
    { cwd: root, env: { ...process.env, PROFILE }, stdio: 'pipe' });
}
